  const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
  let lang = "en";

  function num(v) {
    const s = String(v);
    return lang === "bn" ? s.replace(/[0-9]/g, (d) => BN_DIGITS[d]) : s;
  }

  function t(key, vars) {
    let s = (STR[lang] && STR[lang][key]) || STR.en[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (typeof vars[k] === "number" ? num(vars[k]) : vars[k]) : m));
    return s;
  }

  // Fill every [data-i18n] (text) and [data-i18n-html] (trusted markup from STR) under root.
  function apply(root) {
    const r = root || document;
    r.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    r.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    document.documentElement.lang = lang;
  }

  function setLang(l) {
    lang = STR[l] ? l : "en";
    apply();
  }

  window.SaatI18n = { t, num, apply, setLang, get lang() { return lang; } };
